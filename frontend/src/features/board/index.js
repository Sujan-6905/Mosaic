// Composed from hooks in dependency order: each reads what earlier ones put on `board` and adds its own.
const Whiteboard = (props) => {
    const board = { ...props };
    Object.assign(board, useBoardRefs());
    Object.assign(board, useBoardState(board));
    Object.assign(board, useBoardCore(board));
    Object.assign(board, useBoardSocket(board));
    Object.assign(board, useBoardCollab(board));
    Object.assign(board, useBoardPainting(board));
    Object.assign(board, useOverlayPainting(board));
    Object.assign(board, useBoardViewport(board));
    Object.assign(board, useHitTesting(board));
    Object.assign(board, useElementMutations(board));
    Object.assign(board, useSelectionCommands(board));
    Object.assign(board, useBoardHistory(board));
    Object.assign(board, useSelectionBridge(board));
    Object.assign(board, useTextEditing(board));
    Object.assign(board, useToolLifecycle(board));
    Object.assign(board, useBoardExport(board));
    Object.assign(board, useBoardFind(board));
    Object.assign(board, useWorkshop(board));
    Object.assign(board, useStampTool(board));
    Object.assign(board, useBoardPanels(board));
    Object.assign(board, useBoardImport(board));
    Object.assign(board, useBoardClearing(board));
    Object.assign(board, useAiPlacement(board));
    Object.assign(board, useMermaidImport(board));
    Object.assign(board, usePieces(board));
    Object.assign(board, useDiagramRestyle(board));
    Object.assign(board, useElementDragStart(board));
    Object.assign(board, useConnectorTools(board));
    Object.assign(board, useFlowchartKeys(board));
    Object.assign(board, usePlacementTools(board));
    Object.assign(board, useBucketFill(board));
    Object.assign(board, useImageInsert(board));
    Object.assign(board, useEmbeds(board));
    Object.assign(board, useBoardClipboard(board));
    Object.assign(board, useBoardKeyboard(board));
    Object.assign(board, useBoardContextMenu(board));
    Object.assign(board, useHoverFeedback(board));
    Object.assign(board, usePointerDown(board));
    Object.assign(board, usePointerMove(board));
    Object.assign(board, usePointerUp(board));
    Object.assign(board, useBoardGestures(board));
    useEdgeAutoPan(board);
    useCustomFonts(board);
    Object.assign(board, useBoardDerived(board));
    useSelectionActions(board);

    return <BoardView board={board} />;
};

export default memo(Whiteboard);
